"""Reproducibility smoke test: clone the repo into a temp dir, empty its runs/, download Fashion-MNIST and run
every experiment stage with --smoke (tiny fixed subsets, one epoch per training run) in dependency order.
The committed runs/ of this checkout are never touched; only the summary is written here.

Usage:
  python scripts/smoke_test.py                       # clone HEAD
  python scripts/smoke_test.py --uncommitted         # also apply the working-tree diff + untracked files
  python scripts/smoke_test.py --keep                # keep the temp clone for inspection
Writes runs/smoke_test.json (per-step status and seconds). Exit code 1 on the first failing step.
"""

import argparse
import json
import os
import platform
import shutil
import subprocess
import sys
import tempfile
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "runs", "smoke_test.json")

# (module, args); every step gets --smoke. Order = dependency order of the real pipeline.
STEPS = [
    ("experiments.show_data", []),
    ("experiments.mlp", ["sweep"]),
    ("experiments.mlp", ["failures"]),
    ("experiments.mlp", ["run", "--tag", "fix", "--opt", "adam", "--lr", "3e-4", "--dropout", "0.3", "--wd", "0.05"]),
    ("experiments.mlp", ["test"]),
    ("experiments.diagnose_overfit", []),
    ("experiments.cnn", ["train"]),
    ("experiments.cnn", ["retry"]),
    ("experiments.cnn", ["test"]),
    ("experiments.cnn", ["shift"]),
    ("experiments.cnn", ["ablation"]),
    ("experiments.cnn_ablation", []),
    ("experiments.quant", ["B"]),
    ("experiments.robust", ["finder"]),
    ("experiments.robust", ["augspeed"]),
    ("experiments.robust", ["train"]),
    ("experiments.robust", ["eval"]),
    ("experiments.robust", ["plot"]),
    ("experiments.robust", ["select"]),
    ("experiments.distill", ["teachers"]),
    ("experiments.distill", ["cache"]),
    ("experiments.distill", ["candidates"]),
    ("experiments.distill", ["speed"]),
    ("experiments.distill", ["screen"]),
    ("experiments.distill", ["select_arch"]),
    ("experiments.distill", ["cache_cropflip"]),
    ("experiments.distill", ["students"]),
    ("experiments.distill", ["final"]),
    ("experiments.distill", ["deliverable"]),
    ("experiments.distill", ["ablation"]),
    ("experiments.plots", ["all"]),
    ("experiments.hidden_eval", ["--selftest"]),
    ("experiments.hidden_eval", ["data/hidden_selftest/idx", "--name", "smoke"]),
    ("pytest", ["-q", "-p", "no:cacheprovider"]),
    ("scripts.make_tables", []),
]


def cpu():
    try:
        return subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"], capture_output=True, text=True,
                              check=True).stdout.strip() + f", {os.cpu_count()} cores"
    except (OSError, subprocess.CalledProcessError):
        return f"{platform.processor() or platform.machine()}, {os.cpu_count()} cores"


def sh(cmd, cwd, **kw):
    return subprocess.run(cmd, cwd=cwd, check=True, **kw)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--uncommitted", action="store_true")
    ap.add_argument("--keep", action="store_true")
    a = ap.parse_args()
    dest = tempfile.mkdtemp(prefix="acenet_smoke_")
    clone = os.path.join(dest, "repo")
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    sh(["git", "clone", "--quiet", ROOT, clone], ROOT)
    if a.uncommitted:
        diff = subprocess.run(["git", "diff", "HEAD", "--binary"], cwd=ROOT, capture_output=True).stdout
        if diff:
            sh(["git", "apply", "--whitespace=nowarn"], clone, input=diff)
        untracked = subprocess.run(["git", "ls-files", "--others", "--exclude-standard"], cwd=ROOT,
                                   capture_output=True, text=True).stdout.split()
        for f in untracked:
            os.makedirs(os.path.dirname(os.path.join(clone, f)) or clone, exist_ok=True)
            shutil.copy2(os.path.join(ROOT, f), os.path.join(clone, f))
    runs = os.path.join(clone, "runs")
    shutil.rmtree(runs)  # start from nothing: every json/csv/png is regenerated by the steps below
    os.makedirs(runs)
    env = dict(os.environ, ACE_SMOKE="1", PYTHONUNBUFFERED="1", MPLBACKEND="Agg")
    log_path = os.path.join(dest, "smoke.log")
    res = {"head": head, "uncommitted_applied": a.uncommitted, "clone": clone, "python": platform.python_version(),
           "platform": platform.platform(), "cpu": cpu(),
           "numpy": subprocess.run([sys.executable, "-c", "import numpy; print(numpy.__version__)"],
                                   capture_output=True, text=True).stdout.strip(), "steps": []}
    t_all = time.perf_counter()
    t0 = time.perf_counter()
    sh([sys.executable, "-c", "from acenet.data import download; download()"], clone, env=env)
    res["download_s"] = time.perf_counter() - t0
    ok = True
    with open(log_path, "w") as log:
        for mod, args in STEPS:
            cmd = [sys.executable, "-m", mod, *args] + ([] if mod == "pytest" else ["--smoke"])
            if mod == "scripts.make_tables":  # the README tables also cite this run: give them the steps so far
                with open(os.path.join(runs, "smoke_test.json"), "w") as f:
                    json.dump(dict(res, total_s=time.perf_counter() - t_all, **{"pass": True}), f)
            t0 = time.perf_counter()
            log.write(f"\n$ {' '.join(cmd[1:])}\n")
            log.flush()
            step_env = {k: v for k, v in env.items() if k != "ACE_SMOKE"} if mod == "pytest" else env  # full-size tests
            p = subprocess.run(cmd, cwd=clone, env=step_env, stdout=log, stderr=subprocess.STDOUT)
            step = {"cmd": " ".join(["python", "-m", *cmd[2:]]), "rc": p.returncode,
                    "s": round(time.perf_counter() - t0, 1)}
            res["steps"].append(step)
            print(("ok  " if p.returncode == 0 else "FAIL"), f"{step['s']:7.1f}s", step["cmd"], flush=True)
            if p.returncode:
                ok = False
                with open(log_path) as f:
                    res["error_tail"] = f.read()[-3000:]
                print(res["error_tail"])
                break
    res["total_s"] = round(time.perf_counter() - t_all, 1)
    res["pass"] = ok and len(res["steps"]) == len(STEPS)
    if not a.keep and ok:
        shutil.rmtree(dest)
    else:
        res["log"] = log_path
    with open(OUT, "w") as f:
        json.dump(res, f, indent=2)
    print("SMOKE", "PASS" if res["pass"] else "FAIL", f"{res['total_s']:.0f}s", "(log kept: " + log_path + ")" if
          "log" in res else "")
    raise SystemExit(0 if res["pass"] else 1)


if __name__ == "__main__":
    main()
